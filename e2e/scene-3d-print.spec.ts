import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

test.use({ launchOptions: { args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } });

test('simulates lighting, retains orbit settings and includes an optional 3D sheet in print/PDF', async ({ page }) => {
  test.slow();
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.getByPlaceholder('Production title (e.g. The Long Walk Home)').fill('Lighting and 3D print');
  await page.getByLabel(/Start with the example scenes/).check();
  await page.getByRole('button', { name: 'Full Production', exact: true }).click();
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('button', { name: 'Live 3D', exact: true }).click();
  const live = page.getByRole('region', { name: 'Live 3D view' });
  await live.getByLabel('Simulate lighting', { exact: true }).check();
  const scene = live.getByRole('img', { name: '3D scene preview', exact: true });
  await expect(scene).toBeVisible();
  const before = await scene.evaluate(element => (element as HTMLCanvasElement).toDataURL());
  await live.getByRole('slider', { name: 'Ambient light', exact: true }).fill('0.65');
  await expect.poll(() => scene.evaluate(element => (element as HTMLCanvasElement).toDataURL())).not.toBe(before);
  const box = (await scene.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 20, { steps: 8 });
  await page.mouse.up();
  const rotation = await live.getByRole('slider', { name: 'Rotate', exact: true }).inputValue();
  await page.getByTitle('Export & Print Studio', { exact: true }).click();
  await page.getByLabel('Include 3D view in print / PDF', { exact: true }).check();
  const print = page.getByRole('region', { name: 'Printed 3D view' });
  const image = print.getByRole('img');
  await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(1600);
  await expect(page.getByRole('slider', { name: 'Print 3D rotation', exact: true })).toHaveValue(rotation);
  await expect(print).toContainText('Approximate direct lighting');
  await page.emulateMedia({ media: 'print' });
  await expect(live).toBeHidden();
  await expect(image).toBeVisible();
  await expect(page.getByLabel('Include 3D view in print / PDF', { exact: true })).toBeHidden();
  await page.emulateMedia({ media: 'screen' });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  const download = await downloadPromise;
  expect(await download.failure()).toBeNull();
  await download.saveAs(test.info().outputPath('floorplan-3d.pdf'));
  const bytes = await readFile((await download.path())!);
  const { PDFDocument } = createRequire(import.meta.url)('pdf-lib/cjs/index.js') as typeof import('pdf-lib');
  expect((await PDFDocument.load(bytes)).getPageCount()).toBe(2);
  await page.getByLabel('Include 3D view in print / PDF', { exact: true }).uncheck();
  await expect(print).toHaveCount(0);
});
