import type { FloorPlanElement, GridSettings, PlanLayer } from '../../types';
import { HOST_CLEARANCE_MM } from './editWallOpenings';
import { getClosestPointOnSegment } from '../../utils/geometry';
import { buildPlanArchitecture, PREVIEW_DIMENSIONS_MM } from './planArchitecture';

type Command = { command: string; args: Record<string, unknown> };
const BASE_TYPES = {
  wall: 'Gypsum Partition 10 cm',
  door: 'Door 80x210',
  window: 'Window 120x120',
};

const metres = (mm: number) => mm / 1000;
const cadPoint = (point: { x: number; y: number }) => [metres(point.x), metres(-point.y)];

export function buildConstructCadMacro(
  title: string,
  elements: readonly FloorPlanElement[],
  layers: readonly PlanLayer[] | undefined,
  grid: GridSettings,
) {
  const architecture = buildPlanArchitecture(elements, layers, grid);
  const walls = architecture?.walls.filter((wall) => wall.lengthMm >= 1) ?? [];
  if (!architecture || !walls.length) return null;

  const { wallHeight, doorHeight, windowHead, windowSill } = PREVIEW_DIMENSIONS_MM;
  const commands: Command[] = [{ command: 'project_info_set', args: { name: title } }];
  const types = new Map<string, string>();
  let exportedOpenings = 0;

  function ensureType(kind: keyof typeof BASE_TYPES, sizeMm: number) {
    const key = `${kind}:${sizeMm}`;
    const existing = types.get(key);
    if (existing) return existing;

    const name = `Cineplan ${kind} ${types.size + 1}`;
    commands.push({ command: 'type_duplicate', args: { type: BASE_TYPES[kind], name } });
    if (kind === 'wall') {
      commands.push({
        command: 'type_set',
        args: { type: name, params: { layers: [{ material: 'Gypsum', thickness: metres(sizeMm), function: 'Structure' }] } },
      });
    } else {
      const height = kind === 'door' ? doorHeight : windowHead - windowSill;
      for (const [parameter, value] of [['Width', metres(sizeMm)], ['Height', metres(height)]] as const) {
        commands.push({ command: 'component_param_set', args: { type: name, name: parameter, value } });
      }
    }
    types.set(key, name);
    return name;
  }

  for (const wall of walls) {
    commands.push({
      command: 'wall_create',
      args: { start: cadPoint(wall.start), end: cadPoint(wall.end), height: metres(wallHeight), type: ensureType('wall', wall.thicknessMm) },
    });
  }

  for (const wall of walls) {
    const dx = wall.end.x - wall.start.x;
    const dy = wall.end.y - wall.start.y;
    for (const opening of wall.openings) {
      const startMm = opening.start * wall.lengthMm;
      const endMm = opening.end * wall.lengthMm;
      if (startMm < HOST_CLEARANCE_MM || wall.lengthMm - endMm < HOST_CLEARANCE_MM) continue;

      const center = (opening.start + opening.end) / 2;
      const point = { x: wall.start.x + dx * center, y: wall.start.y + dy * center };
      // The documented macro format has no variables for wall IDs. Avoid
      // letting ConstructCAD's point-based host lookup choose an ambiguous wall.
      if (walls.some((other) => other !== wall && getClosestPointOnSegment(point, other.start, other.end).distance < 0.001)) continue;

      const door = architecture.doorsById.get(opening.elementId);
      const angle = (door?.rotation ?? 0) * Math.PI / 180;
      const reversed = dx * Math.cos(angle) + dy * Math.sin(angle) < 0;
      commands.push({
        command: opening.kind === 'door' ? 'door_create' : 'window_create',
        args: {
          point: cadPoint(point),
          type: ensureType(opening.kind, endMm - startMm),
          sill: opening.kind === 'door' ? 0 : metres(windowSill),
          ...(door ? { flip_hand: (door.swingDirection === 'right') !== reversed } : {}),
        },
      });
      exportedOpenings++;
    }
  }

  const skippedOpenings = architecture.openingCount - exportedOpenings;
  const text = [
    '// Generated by Cineplan for a fresh English ConstructCAD project.',
    '// ccad --lang en --save-as floor-plan.ccad script floor-plan.ccmacro',
    `// Visible openings omitted (free-standing, ambiguous, or too close to a wall end): ${skippedOpenings}.`,
    ...commands.map((command) => JSON.stringify(command)),
    '',
  ].join('\n');
  return { text, skippedOpenings };
}
