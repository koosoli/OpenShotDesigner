import ts from 'typescript';
import { writeFileSync } from 'node:fs';

// Generate a closed runtime schema from the SAME interfaces the editor consumes.
// Run explicitly after project-type changes; no network or code evaluation is used.
const program = ts.createProgram(['src/types/index.ts'], { strict: true, target: ts.ScriptTarget.ES2022, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext });
const checker = program.getTypeChecker();
type Schema = { kind: string; value?: unknown; choices?: Schema[]; item?: Schema; properties?: Record<string, Schema>; required?: string[]; additional?: Schema };
function describe(type: ts.Type, depth = 0): Schema {
  if (depth > 16) throw new Error('Recursive collaboration type requires an explicit design.');
  if (type.isUnion()) {
    const choices = type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined)).map((t) => describe(t, depth + 1));
    return choices.length === 1 ? choices[0] : { kind: 'union', choices };
  }
  if (type.isStringLiteral() || type.isNumberLiteral()) return { kind: 'literal', value: type.value };
  if (type.flags & ts.TypeFlags.BooleanLiteral) return { kind: 'literal', value: checker.typeToString(type) === 'true' };
  if (type.flags & ts.TypeFlags.Null) return { kind: 'literal', value: null };
  if (type.flags & ts.TypeFlags.String) return { kind: 'string' };
  if (type.flags & ts.TypeFlags.Number) return { kind: 'number' };
  if (type.flags & ts.TypeFlags.Boolean) return { kind: 'boolean' };
  if (checker.isArrayType(type) || checker.isTupleType(type)) {
    const item = checker.getIndexTypeOfType(type, ts.IndexKind.Number);
    if (!item) throw new Error('Missing array item type.');
    return { kind: 'array', item: describe(item, depth + 1) };
  }
  if (type.flags & ts.TypeFlags.Object) {
    const properties: Record<string, Schema> = {};
    const required: string[] = [];
    for (const property of checker.getPropertiesOfType(type)) {
      const declaration = property.valueDeclaration ?? property.declarations?.[0];
      if (!declaration) throw new Error(`Missing property declaration: ${property.name}`);
      properties[property.name] = describe(checker.getTypeOfSymbolAtLocation(property, declaration), depth + 1);
      if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name);
    }
    const additional = checker.getIndexTypeOfType(type, ts.IndexKind.String);
    return { kind: 'object', properties, required, ...(additional ? { additional: describe(additional, depth + 1) } : {}) };
  }
  throw new Error(`Unsupported collaboration type: ${checker.typeToString(type)}`);
}
const source = program.getSourceFile('src/types/index.ts')!;
const names = ['FloorPlanElement', 'Shot', 'PlanLayer', 'PlanGroup', 'GridSettings', 'SunSettings'];
const result: Record<string, Schema> = {};
for (const statement of source.statements) {
  if ((ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement)) && names.includes(statement.name.text)) result[statement.name.text] = describe(checker.getTypeAtLocation(statement));
}
if (Object.keys(result).length !== names.length) throw new Error('Missing collaboration schema type.');
writeFileSync('src/collaboration/projectSchema.ts', '// Generated by scripts/generate-collaboration-schema.ts; review alongside editor type changes.\nexport const PROJECT_SCHEMA = ' + JSON.stringify(result, null, 2) + ' as const;\n', 'utf8');
console.log(`Generated ${Object.keys(result).length} closed collaboration schemas.`);
